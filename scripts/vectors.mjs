// Writes lib/vectors.js: the seed vocabulary embedded once, so a fresh checker
// (a cold API instance, or a first scan in the browser) only embeds the ingredients.
// Run after changing lib/vocabulary.js: npm run vectors
import { writeFile } from 'node:fs/promises';
import { loadModel, DEFAULT_MODEL } from '../lib/model.js';
import { SEED_TERMS } from '../lib/index.js';

const engine = await loadModel({ model: DEFAULT_MODEL, dtype: 'q8' });
const terms = [...SEED_TERMS].sort();
const vecs = await engine.embed(terms);
const dims = vecs[0].length;
const all = new Float32Array(terms.length * dims);
vecs.forEach((v, i) => all.set(v, i * dims));
const data = Buffer.from(all.buffer).toString('base64');

const out = `// Generated by scripts/vectors.mjs. Do not edit. Float32, little-endian, base64.
export default ${JSON.stringify({ model: engine.model, dtype: engine.dtype, dims, terms })
  .replace(/}$/, `,"data":"${data}"}`)};
`;
await writeFile(new URL('../lib/vectors.js', import.meta.url), out);
console.log(`lib/vectors.js: ${terms.length} terms x ${dims} dims, ${(out.length / 1024).toFixed(0)} KB`);
